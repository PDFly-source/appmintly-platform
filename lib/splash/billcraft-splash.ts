/**
 * BillCraft launch splash — the owner-supplied `BillCraft_Splash.html`, drawn
 * with the platform Canvas so the first frame is ready with the activity's
 * first layout. No WebView, no network, no animation framework.
 *
 * Provenance: docs/splash/BillCraft_Splash.html. Tests/billcraft-splash.test.ts
 * re-extracts both embedded JPEGs from that file and compares their SHA-256
 * digests, so the bytes shipped in the APK are the owner's artwork.
 *
 * Final CSS cascade, as actually rendered (later rules win):
 *   .sp        radial-gradient(circle at 50% 40%, #fff, #ece4ff 88%) over #f4efff
 *   .go .mk    animation: fall .9s cubic-bezier(.3,.7,.3,1) .2s both
 *              (the earlier `zoom 1s ...` declaration is overridden)
 *   .go .tx    animation: rise .8s ease .9s both
 *   .go .rp    animation: rip 1.8s ease-out 1s both   (2nd ripple delay 1.35s)
 *   .steps i:after  animation: fill .6s ease both; delay .9s / 1.5s / 2.1s
 *   .pb        styled but absent from the markup — the three segments are the bar
 *   @media(prefers-reduced-motion:reduce){ *{animation:none!important} }
 */

import {
  BILLCRAFT_SPLASH_LOGO_JPEG_BASE64,
  BILLCRAFT_SPLASH_WORD_JPEG_BASE64,
} from './billcraft-splash-assets';

export const BILLCRAFT_SPLASH_PACKAGE = 'com.appforge.billcraft';

/** Reference `window.SPLASH_MS`. */
export const BILLCRAFT_SPLASH_MS = 3400;

/** Reference page colour: the `html,body` background behind the splash. */
export const BILLCRAFT_SPLASH_BG = '#F4EFFF';

/** Startup safety net: the splash can never outlive this. */
export const BILLCRAFT_SPLASH_HARD_TIMEOUT_MS = 12000;

export const BILLCRAFT_SPLASH_LOGO_NAME = 'billcraft_splash_logo';
export const BILLCRAFT_SPLASH_WORD_NAME = 'billcraft_splash_word';
export const BILLCRAFT_SPLASH_ICON_NAME = 'billcraft_splash_transparent_icon';

/** The two embedded images, extracted byte-for-byte from the reference HTML. */
export function billcraftSplashLogoJpeg(): Buffer {
  return Buffer.from(BILLCRAFT_SPLASH_LOGO_JPEG_BASE64, 'base64');
}

export function billcraftSplashWordJpeg(): Buffer {
  return Buffer.from(BILLCRAFT_SPLASH_WORD_JPEG_BASE64, 'base64');
}

/** colors.xml entries that only the BillCraft build receives. */
export function billcraftSplashColorEntries(): string {
  return `    <color name="billcraft_splash_bg">${BILLCRAFT_SPLASH_BG}</color>`;
}

/**
 * Launch theme. The window background is the reference page colour, so there is
 * no colour break before the animated view draws and no older gradient anywhere.
 */
export function billcraftSplashStylesXml(): string {
  return `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <style name="AppTheme" parent="@android:style/Theme.NoTitleBar">
        <item name="android:windowBackground">@color/billcraft_splash_bg</item>
    </style>
</resources>`;
}

