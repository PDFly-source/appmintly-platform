/**
 * The complete `BillCraftSplashView.java` source. Pure Canvas drawing: no
 * WebView, no network, no animation framework, no external assets.
 */
export function billcraftSplashJava(packageId: string): string {
  return `package ${packageId};

import android.content.Context;
import android.graphics.Bitmap;
import android.graphics.BitmapFactory;
import android.graphics.Canvas;
import android.graphics.Paint;
import android.graphics.PorterDuff;
import android.graphics.PorterDuffXfermode;
import android.graphics.RadialGradient;
import android.graphics.RectF;
import android.graphics.Shader;
import android.provider.Settings;
import android.view.View;

/**
 * BillCraft launch splash — the owner-supplied BillCraft_Splash.html, drawn with
 * the platform Canvas. Generated by lib/splash/billcraft-splash.ts; do not edit
 * the generated copy.
 */
public class BillCraftSplashView extends View {

    public interface OnSplashFinishedListener {
        void onSplashFinished();
    }

    /** Reference window.SPLASH_MS. */
    private static final long DURATION_MS = ${BILLCRAFT_SPLASH_MS}L;

    // ---- reference stage (CSS px == dp) ----
    private static final float STAGE_W = 228f;
    private static final float STAGE_H = 488f;
    private static final float CTR_GAP = 12f;           // .ctr gap
    private static final float CTR_PAD_BOTTOM = 44f;    // .ctr padding-bottom
    private static final float LOGO_W = 130f;           // .mk inline width
    private static final float WORD_W = 190f;           // .tx inline width
    private static final float RIPPLE_D = 120f;         // .rp width/height
    private static final float RIPPLE_CX = 114f;        // .cc left:50%
    private static final float RIPPLE_CY = 190f;        // .cc top:190px
    private static final float RIPPLE_STROKE = 2f;      // .rp border
    private static final float STEPS_INSET = 60f;       // .steps left/right
    private static final float STEPS_BOTTOM = 52f;      // .steps bottom
    private static final float STEPS_GAP = 6f;          // .steps gap
    private static final float STEPS_H = 4f;            // .steps i height
    private static final float STEPS_R = 4f;            // .steps i radius

    // radial-gradient(circle at 50% 40%, #fff, #ece4ff 88%): the default
    // farthest-corner circle from that centre, in stage units.
    private static final float GRAD_CX = 114f;
    private static final float GRAD_CY = 195.2f;
    private static final float GRAD_R = 314.2f;
    private static final float GRAD_STOP = 0.88f;

    // ---- palette (final cascade) ----
    private static final int CANVAS = 0xFFF4EFFF;       // html,body background
    private static final int GRAD_INNER = 0xFFFFFFFF;   // #fff
    private static final int GRAD_OUTER = 0xFFECE4FF;   // #ece4ff
    private static final int RIPPLE_COLOR = 0xFF17C3A0; // #17c3a0
    private static final int SEG_TRACK = 0x245B21B6;    // rgba(91,33,182,.14)
    private static final int SEG_1 = 0xFF6D28D9;        // #6d28d9
    private static final int SEG_2 = 0xFF6D28D9;        // #6d28d9
    private static final int SEG_3 = 0xFF17C3A0;        // #17c3a0

    // ---- timeline: delay + duration from the final declarations ----
    private static final long LOGO_DELAY = 200L, LOGO_DUR = 900L;    // fall
    private static final long WORD_DELAY = 900L, WORD_DUR = 800L;    // rise
    private static final long RIPPLE_DUR = 1800L;                    // rip
    private static final long RIPPLE_DELAY_1 = 1000L, RIPPLE_DELAY_2 = 1350L;
    private static final long SEG_DUR = 600L;                        // fill
    private static final long SEG_DELAY_1 = 900L, SEG_DELAY_2 = 1500L, SEG_DELAY_3 = 2100L;

    // @keyframes fall — 0%, 55%, 78%, 100%
    private static final float[] FALL_AT = {0f, 0.55f, 0.78f, 1f};
    private static final float[] FALL_OPACITY = {0f, 1f, 1f, 1f};
    private static final float[] FALL_Y = {-100f, 8f, -3f, 0f};
    private static final float[] FALL_SCALE = {0.9f, 1f, 1f, 1f};

    private final float density;
    private final boolean reducedMotion;
    private final Bitmap logo;
    private final Bitmap word;
    private final Paint paint = new Paint(Paint.ANTI_ALIAS_FLAG);
    private final Paint logoPaint = new Paint(Paint.FILTER_BITMAP_FLAG);
    private final Paint wordPaint = new Paint(Paint.FILTER_BITMAP_FLAG);

    private boolean running;
    private boolean finished;
    private long startNs = -1L;
    private OnSplashFinishedListener listener;

    public BillCraftSplashView(Context context) {
        super(context);
        density = getResources().getDisplayMetrics().density;
        reducedMotion = isReducedMotion();
        logo = loadBitmap("${BILLCRAFT_SPLASH_LOGO_NAME}");
        word = loadBitmap("${BILLCRAFT_SPLASH_WORD_NAME}");
        // The reference draws both images with mix-blend-mode:multiply over the
        // gradient, so they have to blend with the backdrop rather than sit on
        // it. Blend modes need a software layer to be honoured.
        logoPaint.setXfermode(new PorterDuffXfermode(PorterDuff.Mode.MULTIPLY));
        wordPaint.setXfermode(new PorterDuffXfermode(PorterDuff.Mode.MULTIPLY));
        setLayerType(LAYER_TYPE_SOFTWARE, null);
        setBackgroundColor(CANVAS);
        setContentDescription("BillCraft");
    }

    public void setOnSplashFinishedListener(OnSplashFinishedListener l) {
        listener = l;
    }

    /** Restarts the timeline (used when the view is re-attached to a window). */
    public void restart() {
        startNs = -1L;
        finished = false;
        invalidate();
    }

    @Override
    protected void onAttachedToWindow() {
        super.onAttachedToWindow();
        if (startNs < 0L) {
            startNs = System.nanoTime();
            running = true;
            postInvalidateOnAnimation();
        }
    }

    @Override
    protected void onDetachedFromWindow() {
        running = false;
        super.onDetachedFromWindow();
    }

    private float elapsedMs() {
        if (startNs < 0L) return 0f;
        return (System.nanoTime() - startNs) / 1000000f;
    }

    private Bitmap loadBitmap(String name) {
        try {
            final int id = getResources().getIdentifier(name, "drawable", getContext().getPackageName());
            if (id == 0) return null;
            return BitmapFactory.decodeResource(getResources(), id);
        } catch (Throwable ignored) {
            return null;
        }
    }

    @Override
    protected void onDraw(Canvas canvas) {
        super.onDraw(canvas);
        final int w = getWidth();
        final int h = getHeight();
        if (w <= 0 || h <= 0) return;

        final float t = reducedMotion ? DURATION_MS : elapsedMs();

        // fit(): the stage is scaled by min(viewport/228, viewport/488) exactly
        // like the reference's --k, so the composition matches the browser at
        // every aspect ratio; the artwork itself is never stretched.
        final float stageW = STAGE_W * density;
        final float stageH = STAGE_H * density;
        final float k = Math.min(w / stageW, h / stageH);
        final float u = density * k;
        final float ox = (w - stageW * k) / 2f;
        final float oy = (h - stageH * k) / 2f;

        // 1. background: radial-gradient(circle at 50% 40%, #fff, #ece4ff 88%)
        paint.setStyle(Paint.Style.FILL);
        canvas.drawColor(CANVAS);
        paint.setShader(new RadialGradient(
                ox + GRAD_CX * u, oy + GRAD_CY * u, GRAD_R * u,
                new int[]{GRAD_INNER, GRAD_OUTER},
                new float[]{0f, GRAD_STOP},
                Shader.TileMode.CLAMP));
        canvas.drawRect(0f, 0f, w, h, paint);
        paint.setShader(null);

        // 2. ripples behind the artwork (.rp, two staggered rings)
        if (!reducedMotion) {
            paint.setStyle(Paint.Style.STROKE);
            paint.setStrokeWidth(RIPPLE_STROKE * u);
            paint.setColor(RIPPLE_COLOR);
            final float rcx = ox + RIPPLE_CX * u;
            final float rcy = oy + RIPPLE_CY * u;
            drawRipple(canvas, rcx, rcy, u, t, RIPPLE_DELAY_1);
            drawRipple(canvas, rcx, rcy, u, t, RIPPLE_DELAY_2);
            paint.setStyle(Paint.Style.FILL);
            paint.setAlpha(255);
        }

        if (logo == null || word == null) {
            finishIfDue(t);
            return;
        }

        // 3. centred column: logo, 12dp gap, wordmark; padding-bottom 44dp
        final float colCx = ox + (STAGE_W / 2f) * u;
        final float logoW = LOGO_W * u;
        final float logoH = logoW * ((float) logo.getHeight() / (float) logo.getWidth());
        final float wordW = WORD_W * u;
        final float wordH = wordW * ((float) word.getHeight() / (float) word.getWidth());
        final float contentH = logoH + CTR_GAP * u + wordH;
        final float areaH = (STAGE_H - CTR_PAD_BOTTOM) * u;
        final float top = oy + Math.max(0f, (areaH - contentH) / 2f);

        // 3a. logo: animation fall .9s cubic-bezier(.3,.7,.3,1) .2s both
        if (reducedMotion) {
            logoPaint.setAlpha(255);
            drawArtwork(canvas, logo, colCx, top + logoH / 2f, logoW, logoH, 1f, logoPaint);
        } else {
            final float p = progress(t, LOGO_DELAY, LOGO_DUR);
            final float[] op = new float[1];
            final float[] ty = new float[1];
            final float[] sc = new float[1];
            fallState(p, op, ty, sc);
            logoPaint.setAlpha(Math.round(255f * clamp01(op[0])));
            drawArtwork(canvas, logo, colCx, top + logoH / 2f + ty[0] * u, logoW, logoH, sc[0], logoPaint);
        }

        // 3b. wordmark: animation rise .8s ease .9s both
        final float wp = reducedMotion ? 1f : progress(t, WORD_DELAY, WORD_DUR);
        final float we = reducedMotion ? 1f : ease(wp, 0.25f, 0.1f, 0.25f, 1f);
        final float wordTop = top + logoH + CTR_GAP * u;
        wordPaint.setAlpha(Math.round(255f * clamp01(we)));
        drawArtwork(canvas, word, colCx, wordTop + wordH / 2f + (18f * (1f - we)) * u,
                wordW, wordH, 1f, wordPaint);

        // 4. loading indicator: three segments (.steps), filled in sequence
        final float segLeft = ox + STEPS_INSET * u;
        final float segRight = ox + (STAGE_W - STEPS_INSET) * u;
        final float segTop = oy + (STAGE_H - STEPS_BOTTOM - STEPS_H) * u;
        final float segW = (segRight - segLeft - 2f * STEPS_GAP * u) / 3f;
        final float segH = STEPS_H * u;
        final float segR = STEPS_R * u;
        final int[] colors = new int[]{SEG_1, SEG_2, SEG_3};
        final long[] delays = new long[]{SEG_DELAY_1, SEG_DELAY_2, SEG_DELAY_3};
        for (int i = 0; i < 3; i++) {
            final float left = segLeft + i * (segW + STEPS_GAP * u);
            final RectF track = new RectF(left, segTop, left + segW, segTop + segH);
            paint.setColor(SEG_TRACK);
            canvas.drawRoundRect(track, segR, segR, paint);
            if (reducedMotion) continue;
            final float fp = ease(progress(t, delays[i], SEG_DUR), 0.25f, 0.1f, 0.25f, 1f);
            if (fp <= 0f) continue;
            paint.setColor(colors[i]);
            canvas.drawRoundRect(
                    new RectF(left, segTop, left + segW * clamp01(fp), segTop + segH),
                    segR, segR, paint);
        }

        finishIfDue(t);
    }

    /** One ripple: rip 1.8s ease-out <delay> both — .8 → 0 opacity, .8 → 3 scale. */
    private void drawRipple(Canvas canvas, float cx, float cy, float u, float t, long delay) {
        final float p = progress(t, delay, RIPPLE_DUR);
        if (p >= 1f) return; // to-state is fully transparent
        final float e = ease(p, 0f, 0f, 0.58f, 1f);
        final float opacity = 0.8f + (0f - 0.8f) * e;
        final float scale = 0.8f + (3f - 0.8f) * e;
        if (opacity <= 0.004f) return;
        paint.setAlpha(Math.round(255f * opacity));
        canvas.drawCircle(cx, cy, (RIPPLE_D / 2f) * u * scale, paint);
        paint.setAlpha(255);
    }

    /** Serialises a bitmap with its own scale about the column centre. */
    private void drawArtwork(Canvas canvas, Bitmap bmp, float cx, float cy,
                             float w, float h, float scale, Paint p) {
        if (p.getAlpha() == 0) return;
        final int save = canvas.save();
        canvas.translate(cx, cy);
        if (scale != 1f) canvas.scale(scale, scale);
        final RectF dst = new RectF(-w / 2f, -h / 2f, w / 2f, h / 2f);
        canvas.drawBitmap(bmp, null, dst, p);
        canvas.restoreToCount(save);
    }

    /**
     * @keyframes fall, evaluated the way CSS does it: the animation's timing
     * function applies to each keyframe segment, not across the whole run.
     */
    private static void fallState(float p, float[] opacity, float[] ty, float[] scale) {
        final float clamped = clamp01(p);
        int i = 0;
        while (i < FALL_AT.length - 2 && clamped > FALL_AT[i + 1]) i++;
        final float span = FALL_AT[i + 1] - FALL_AT[i];
        final float local = span <= 0f ? 1f : (clamped - FALL_AT[i]) / span;
        final float e = ease(local, 0.3f, 0.7f, 0.3f, 1f);
        opacity[0] = lerp(FALL_OPACITY[i], FALL_OPACITY[i + 1], e);
        ty[0] = lerp(FALL_Y[i], FALL_Y[i + 1], e);
        scale[0] = lerp(FALL_SCALE[i], FALL_SCALE[i + 1], e);
    }

    private void finishIfDue(float t) {
        if (!finished && t >= DURATION_MS) {
            finished = true;
            if (listener != null) listener.onSplashFinished();
        }
        if (running) postInvalidateOnAnimation();
    }

    /** Animation progress 0..1 for a CSS delay/duration pair ("both" fill mode). */
    private static float progress(float t, long delay, long dur) {
        if (dur <= 0L) return t >= delay ? 1f : 0f;
        final float p = (t - delay) / (float) dur;
        return clamp01(p);
    }

    /** CSS cubic-bezier(x1,y1,x2,y2) as a timing function (Newton + bisection). */
    private static float ease(float p, float x1, float y1, float x2, float y2) {
        if (p <= 0f) return 0f;
        if (p >= 1f) return 1f;
        final float[] curveX = {0f, x1, x2, 1f};
        final float[] curveY = {0f, y1, y2, 1f};
        float lo = 0f;
        float hi = 1f;
        float t = p;
        for (int i = 0; i < 24; i++) {
            final float x = bezier(curveX, t);
            if (Math.abs(x - p) < 1e-4f) break;
            if (x < p) lo = t; else hi = t;
            t = (lo + hi) / 2f;
        }
        return bezier(curveY, t);
    }

    private static float bezier(float[] c, float t) {
        final float mt = 1f - t;
        return mt * mt * mt * c[0]
                + 3f * mt * mt * t * c[1]
                + 3f * mt * t * t * c[2]
                + t * t * t * c[3];
    }

    private static float lerp(float a, float b, float s) {
        return a + (b - a) * s;
    }

    private static float clamp01(float v) {
        return v < 0f ? 0f : (v > 1f ? 1f : v);
    }

    /** The reference disables every animation under prefers-reduced-motion. */
    private boolean isReducedMotion() {
        try {
            float scale = Settings.Global.getFloat(
                    getContext().getContentResolver(),
                    Settings.Global.ANIMATOR_DURATION_SCALE, 1f);
            return scale == 0f;
        } catch (Throwable ignored) {
            return false;
        }
    }
}
`;
}
